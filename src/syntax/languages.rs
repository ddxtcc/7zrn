use super::Syntax;

#[derive(Default)]
pub(super) struct Rules {
    pub(super) line_comments: &'static [&'static [u8]],
    pub(super) block_comment: Option<(&'static [u8], &'static [u8])>,
    pub(super) quotes: &'static [u8],
    pub(super) keywords: &'static [&'static str],
    pub(super) literals: &'static [&'static str],
    pub(super) key_separators: &'static [u8],
    pub(super) json_keys: bool,
    pub(super) html: bool,
    pub(super) diff: bool,
}

fn clike(keywords: &'static [&'static str], literals: &'static [&'static str]) -> Rules {
    Rules {
        line_comments: &[b"\x2f\x2f"],
        block_comment: Some((b"/*", b"*/")),
        quotes: b"\"'",
        keywords,
        literals,
        ..Rules::default()
    }
}

fn hash(keywords: &'static [&'static str], literals: &'static [&'static str]) -> Rules {
    Rules {
        line_comments: &[b"#"],
        quotes: b"\"'",
        keywords,
        literals,
        ..Rules::default()
    }
}

fn dash(keywords: &'static [&'static str], literals: &'static [&'static str]) -> Rules {
    Rules {
        line_comments: &[b"--"],
        block_comment: Some((b"/*", b"*/")),
        quotes: b"\"'",
        keywords,
        literals,
        ..Rules::default()
    }
}

